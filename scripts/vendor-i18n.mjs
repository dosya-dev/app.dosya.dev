const RUNTIME = ['icu.ts', 'translator.ts', 'match.ts'];
const GENERATED = 'Generated by scripts/vendor-i18n.mjs from packages/i18n/web. Do not edit by hand: change the catalog and run `npm run vendor:i18n`.';
const json = (v) => JSON.stringify(v, null, 2) + '\n';
const q = (s) => JSON.stringify(s);
const ident = (l) => (/^[a-z]+$/.test(l) ? l : q(l));

// Argument names used anywhere in a parsed message (args, plural/select names).
function argNames(nodes, out = new Set()) {
  for (const n of nodes) {
    if (typeof n === 'string' || n.type === 'pound') continue;
    out.add(n.name);
    if (n.type === 'plural' || n.type === 'select') for (const o of Object.values(n.options)) argNames(o, out);
  }
  return out;
}
function pluralBranches(nodes, out = []) {
  for (const n of nodes) {
    if (typeof n === 'string' || n.type === 'pound' || n.type === 'arg') continue;
    if (n.type === 'plural') out.push(...Object.keys(n.options));
    for (const o of Object.values(n.options)) pluralBranches(o, out);
  }
  return out;
}

// Why a language file cannot ship: a list of problems, empty when it can.
function problems(lang, messages, english, requiredKeys, parseIcu, rtl) {
  const out = [];
  if (RTL_CANDIDATES.includes(lang) && !rtl.includes(lang)) out.push('right-to-left (not supported)');
  const missing = requiredKeys.filter((k) => !(k in messages));
  if (missing.length) out.push(`missing ${missing.length} keys: ${missing.slice(0, 5).join(', ')}${missing.length > 5 ? ', ...' : ''}`);
  const allowed = new Set([...new Intl.PluralRules(lang).resolvedOptions().pluralCategories, 'other']);
  const bad = [];
  for (const [key, text] of Object.entries(messages)) {
    if (!(key in english)) continue;
    let nodes;
    try {
      nodes = parseIcu(text);
    } catch (e) {
      bad.push(`${key} (does not parse)`);
      continue;
    }
    const want = [...argNames(parseIcu(english[key]))].sort().join(',');
    const have = [...argNames(nodes)].sort().join(',');
    if (want !== have) {
      bad.push(`${key} (arguments {${have}} differ from English {${want}})`);
      continue;
    }
    const branch = pluralBranches(nodes).find((b) => !allowed.has(b) && !/^=\d+$/.test(b));
    if (branch) bad.push(`${key} (plural branch "${branch}" not used by ${lang})`);
  }
  if (bad.length) out.push(`invalid ${bad.length} messages: ${bad.slice(0, 5).join('; ')}${bad.length > 5 ? '; ...' : ''}`);
  return out;
}

// icu.ts is TypeScript with no imports: strip its types by transpiling with the
// TypeScript compiler (a devDependency of the repo) and load the result.
async function loadParseIcu(icuPath) {
  const ts = (await import('typescript')).default;
  const out = ts.transpileModule(readFileSync(icuPath, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const mod = await import('data:text/javascript;base64,' + Buffer.from(out).toString('base64'));
  return mod.parseIcu;
}

// Pure: reads the inputs, returns what to write. { files: {relPath: content},
// copies: [[from, to]], shipped, skipped: {lang: [problems]} }. Paths are relative to webRoot.
export async function buildOutputs({ webRoot, desktopRoot, catalogDir, rtl = RTL, allowDrop = [] }) {
  const catalogPath = resolve(catalogDir, 'en.catalog.json');
  if (!existsSync(catalogPath)) throw new Error(`missing ${catalogPath}`);
  const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
  const english = {};
  const requiredKeys = [];
  for (const s of catalog.strings) {
    english[s.key] = s.source;
    if (s.translate !== false) requiredKeys.push(s.key);
  }
  const keys = Object.keys(english).sort();

  const icuPath = resolve(desktopRoot, 'src/i18n/icu.ts');
  if (!existsSync(icuPath)) throw new Error(`missing ${icuPath}`);
  const parseIcu = await loadParseIcu(icuPath);

  const langs = readdirSync(catalogDir)
    .filter((f) => /^[a-z]{2,3}(-[A-Za-z0-9]+)?\.json$/.test(f))
    .map((f) => f.slice(0, -5))
    .filter((l) => l !== 'en');
  for (const l of langs) if (!(l in LABELS)) throw new Error(`${l}.json has no entry in LABELS: add its name in its own language`);
  const ordered = Object.keys(LABELS).filter((l) => langs.includes(l));

  const SHIPPED = [];
  const skipped = {};
  const bodies = {};
  for (const lang of ordered) {
    const messages = JSON.parse(readFileSync(resolve(catalogDir, `${lang}.json`), 'utf8'));
    const extra = Object.keys(messages).filter((key) => !(key in english));
    if (extra.length) throw new Error(`${lang}.json has keys the catalog lacks: ${extra.join(', ')}`);
    const why = problems(lang, messages, english, requiredKeys, parseIcu, rtl);
    if (why.length) skipped[lang] = why;
    else {
      SHIPPED.push(lang);
      bodies[lang] = messages;
    }
  }
  const notShipped = rtl.filter((l) => !SHIPPED.includes(l));
  if (notShipped.length && rtl !== RTL) throw new Error(`RTL entries that are not in SHIPPED: ${notShipped.join(', ')}`);

  const previousPath = resolve(webRoot, 'src/i18n/shipped.json');
  const previous = existsSync(previousPath) ? JSON.parse(readFileSync(previousPath, 'utf8')) : [];
  const dropped = previous.filter((l) => !SHIPPED.includes(l) && !allowDrop.includes(l));
  if (dropped.length) {
    throw new Error(
      `would drop shipped language(s) without --allow-drop: ${dropped.map((l) => `${l} [${(skipped[l] ?? ['file missing']).join(' | ')}]`).join('; ')}`,
    );
  }
  const shippedRtl = rtl.filter((l) => SHIPPED.includes(l));

  const files = {};
  files['src/i18n/messages/en.json'] = json(english);
  for (const lang of SHIPPED) files[`src/i18n/messages/${lang}.json`] = json(bodies[lang]);
  files['src/i18n/shipped.json'] = json(SHIPPED);

  files['src/i18n/keys.ts'] =
    `// ${GENERATED}\n\nexport type MessageKey =\n${keys.map((key) => `  | ${q(key)}`).join('\n')};\n`;

  const all = ['en', ...SHIPPED];
  files['src/i18n/locales.ts'] = [
    `// ${GENERATED}`,
    '',
    '/** The languages the web app ships. English is the source and fallback. */',
    `export type Locale = ${all.map(q).join(' | ')};`,
    '',
    `export const LOCALES: readonly Locale[] = [${all.map(q).join(', ')}];`,
    '',
    'export function isLocale(x: unknown): x is Locale {',
    '  return typeof x === "string" && (LOCALES as readonly string[]).includes(x);',
    '}',
    '',
    "/** Each language's name in itself, for the language picker. */",
    'export const LOCALE_LABELS: Record<Locale, string> = {',
    ...all.map((l) => `  ${ident(l)}: ${q(LABELS[l])},`),
    '};',
    '',
    '/** The right-to-left languages. */',
    `export const RTL_LOCALES: readonly Locale[] = [${shippedRtl.map(q).join(', ')}];`,
    '',
    '/** The layout direction of a language. */',
    'export function localeDir(l: Locale): "ltr" | "rtl" {',
    '  return RTL_LOCALES.includes(l) ? "rtl" : "ltr";',
    '}',
    '',
    '/** The Intl locale tag for a language; English gives undefined (the runtime default). */',
    `const INTL_TAGS: Partial<Record<Locale, string>> = ${JSON.stringify(Object.fromEntries(Object.entries(INTL_TAGS).filter(([l]) => SHIPPED.includes(l))))};`,
    'export function intlTag(l: Locale): string | undefined {',
    '  return l === "en" ? undefined : (INTL_TAGS[l] ?? l);',
    '}',
    '',
  ].join('\n');

  files['src/i18n/loaders.ts'] = [
    `// ${GENERATED}`,
    '',
    'import type { Locale } from "./locales";',
    'import type { Messages } from "./translator";',
    '',
    '/** One chunk per language: each loads only what is chosen. English is bundled where it is used. */',
    'export const LOADERS: Record<Exclude<Locale, "en">, () => Promise<{ default: Messages }>> = {',
    ...SHIPPED.map((l) => `  ${ident(l)}: () => import(${q(`./messages/${l}.json`)}),`),
    '};',
    '',
  ].join('\n');

  const copies = RUNTIME.map((f) => {
    const from = resolve(desktopRoot, 'src/i18n', f);
    if (!existsSync(from)) throw new Error(`missing ${from}`);
    return [from, resolve(webRoot, 'src/i18n', f)];
  });
  return { files, copies, shipped: SHIPPED, skipped };
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const webRoot = resolve(here, '..');
  const desktopRoot = resolve(webRoot, '../desktop');
  const catalogDir = resolve(webRoot, '../../packages/i18n/web');
  const allowDrop = [];
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; i++) if (args[i] === '--allow-drop' && args[i + 1]) allowDrop.push(args[++i]);
  try {
    const { files, copies, shipped, skipped } = await buildOutputs({ webRoot, desktopRoot, catalogDir, allowDrop });
    rmSync(resolve(webRoot, 'src/i18n/messages'), { recursive: true, force: true });
    mkdirSync(resolve(webRoot, 'src/i18n/messages'), { recursive: true });
    for (const [from, to] of copies) cpSync(from, to);
    for (const [rel, content] of Object.entries(files)) writeFileSync(resolve(webRoot, rel), content);
    const external = resolve(webRoot, 'src/i18n/external-keys.ts');
    if (!existsSync(external)) {
      writeFileSync(
        external,
        '/**\n * Catalog keys whose English the app shows without authoring it at the call site;\n * the strict text matcher translates only these. Web\'s own list: never overwritten by\n * scripts/vendor-i18n.mjs.\n */\nimport type { MessageKey } from "./keys";\n\nexport const EXTERNAL_KEYS: readonly MessageKey[] = [];\n',
      );
    }
    for (const [lang, why] of Object.entries(skipped)) console.log(`  not shipped: ${lang}: ${why.join(' | ')}`);
    console.log(`✓ vendored i18n -> apps/web/src/i18n (${shipped.length} languages shipped: ${shipped.join(' ')}; ${copies.length} runtime copies)`);
  } catch (e) {
    console.error(`✖ ${e.message}`);
    process.exit(1);
  }
}
