#!/usr/bin/env node
// Vendor the i18n runtime and the reviewed catalogs into apps/web so the app
// is fully self-contained.
//
// WHY: same reason vendor-e2ee.mjs and vendor-video-player.mjs exist. CI
// (sync-public-repos.yml -> `sync-web`) pushes ONLY `apps/web/` to the deploy
// repo Cloudflare Pages builds, with apps/web as the repo ROOT. In that repo
// there is no `../../packages/` or `../desktop/` sibling, so an import or
// alias pointing there resolves in the monorepo and fails on Cloudflare.
//
// Two things are vendored:
//   1. The ICU runtime (icu.ts, translator.ts, match.ts) from
//      apps/desktop/src/i18n, copied FLAT and unchanged so its relative
//      imports (./icu.ts, ./keys.ts, ./locales.ts, ./external-keys.ts) keep
//      working. Edit them in apps/desktop, then re-run this script.
//   2. The catalogs from packages/i18n/web: en.catalog.json becomes
//      messages/en.json ({key: source}), each SHIPPED language becomes
//      messages/<lang>.json. From them the script generates keys.ts
//      (MessageKey), locales.ts and loaders.ts.
//
// SHIPPED is computed, not hand-listed (same rule as apps/mobile). A language
// ships when it has every catalog key that is not `translate: false`, and every
// message parses, has the English argument names and uses only plural branches
// the language has (Intl.PluralRules, plus other and =N). A right-to-left
// language also needs the app's RTL support (RTL below). A candidate that is
// incomplete stays in LABELS and simply joins on a later run once complete. A
// language shipped before (src/i18n/shipped.json) that would drop out fails the
// run unless named with --allow-drop <lang>. A language file with a key the
// catalog lacks fails the whole run.
// external-keys.ts is web's own list; it is created empty and never
// overwritten.
//
// This is a MONOREPO-ONLY step. Re-run it (`npm run vendor:i18n`) whenever the
// catalogs or the desktop runtime change, then commit src/i18n/.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

// Right-to-left languages the app supports: the direction table below is generated
// from the shipped ones. A right-to-left candidate not listed here never ships.
const RTL = ['ar', 'he', 'fa'];
// Languages written right to left, whether or not the app supports them.
const RTL_CANDIDATES = ['ar', 'he', 'fa', 'ur'];

// Intl tags that differ from the language code. ar is pinned to Western digits so every browser agrees.
// th is pinned to the Gregorian calendar: Intl defaults to Buddhist years (2569) and no glossary asks for them.
const INTL_TAGS = { ar: 'ar-u-nu-latn', th: 'th-u-ca-gregory' };

// Each language in its own name, for the picker (same labels as desktop). Order is the
// picker order. Every candidate language needs an entry; it ships only when complete.
